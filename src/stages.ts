function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function getTodayDateKey(): string {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function buildDailyChallengeStage(dateKey = getTodayDateKey()): StageDef {
  let hash = 2166136261;
  for (let i = 0; i < dateKey.length; i++) {
    hash ^= dateKey.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const rng = mulberry32(hash);
  // Pick a base layout from stages 4..11
  const templatePool = STAGES.slice(3, 11);
  const base = templatePool[Math.floor(rng() * templatePool.length)];

  const mutatorPool: { label: string; apply: (f: StageDef['features']) => void }[] = [
    { label: '🔥 Mayday Surge', apply: (f) => { f.maydayEmergencies = true; } },
    { label: '🛸 UFO Watch', apply: (f) => { f.ufoEvents = true; } },
    { label: '🤖 Drone Swarm', apply: (f) => { f.rogueDrones = true; } },
    { label: '⛈️ Thunderheads', apply: (f) => { f.storms = Math.max(2, f.storms ?? 0); } },
    { label: '💨 Crosswind Flips', apply: (f) => { f.windShifts = true; } },
    { label: '🌙 Twilight Blackout', apply: (f) => { f.dayToNight = true; } },
    { label: '⛽ Fuel Crunch', apply: (f) => { f.lowFuel = true; } },
  ];

  // Shuffle mutators deterministically & pick 3
  const shuffled = [...mutatorPool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  const picked = shuffled.slice(0, 3);
  const features: StageDef['features'] = {
    ...base.features,
    bonusLifeStreak: true,
    vipJets: true,
  };
  for (const m of picked) m.apply(features);

  const dailyTarget = Math.max(20, Math.min(30, base.targetLandings));

  return {
    ...base,
    id: 999,
    name: `Daily Ops • ${base.name}`,
    subtitle: `${dateKey} • 2x ATC Credits`,
    difficulty: 'DAILY OPS',
    targetLandings: dailyTarget,
    targetLaunches: features.outboundTakeoffs ? 5 : undefined,
    maxAirborne: Math.min(8, base.maxAirborne + 1),
    spawnIntervalMin: Math.max(2.6, base.spawnIntervalMin - 0.35),
    spawnIntervalMax: Math.max(4.6, base.spawnIntervalMax - 0.5),
    features,
    isDaily: true,
    dailyDateKey: dateKey,
    dailyMutators: picked.map((p) => p.label),
    tip: `Daily Challenge (${picked.map((p) => p.label).join(' + ')}). Complete for 2x Credits & Daily Streak!`,
  };
}
